JD_TOL = 2e-6  # ~0.2 s
NUM_TOL = 1e-9


def _calc(epoch, lon, lat):
    dt = datetime.fromtimestamp(epoch, tz=timezone.utc)
    calc = sun_moon.SunMoonCalculator(dt, longitude=lon, latitude=lat)
    calc.calc_sun_and_moon()
    return calc


class TestGoldenAgreementWithSwift:
    @pytest.mark.parametrize("label", sorted(GOLDEN))
    def test_moon_age_and_illumination(self, label):
        epoch, lon, lat, age, illum, *_ = GOLDEN[label]
        calc = _calc(epoch, lon, lat)
        assert calc.moon_age == pytest.approx(age, abs=NUM_TOL)
        assert calc.moon_illumination == pytest.approx(illum, abs=NUM_TOL)

    @pytest.mark.parametrize("label", sorted(GOLDEN))
    def test_rise_set_times(self, label):
        epoch, lon, lat, _age, _illum, mrise, mset, srise, sset = GOLDEN[label]
        calc = _calc(epoch, lon, lat)
        assert calc.moon_rise == pytest.approx(mrise, abs=JD_TOL)
        assert calc.moon_set == pytest.approx(mset, abs=JD_TOL)
        assert calc.sun_rise == pytest.approx(srise, abs=JD_TOL)
        assert calc.sun_set == pytest.approx(sset, abs=JD_TOL)


class TestJulianDayConversion:
    def test_round_trip_known_jd(self):
        # JD 2461279.5 is 2026-08-27 00:00 UTC, so .5713 → 01:42 UTC that day.
        dt = sun_moon.jd_to_datetime(2461279.5713060247)
        assert dt.tzinfo is not None
        assert (dt.year, dt.month, dt.day) == (2026, 8, 27)
        assert (dt.hour, dt.minute) == (1, 42)

    def test_no_event_returns_none(self):
        assert sun_moon.jd_to_datetime(-1.0) is None
        assert sun_moon.jd_to_datetime(float("nan")) is None


